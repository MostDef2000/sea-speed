def canonical_name(name: str) -> str:
    """PEP 503-style normalization for lock/manifest name comparisons."""
    return name.strip().lower().replace("_", "-")


def parse_lock_graph(text: str) -> dict[str, dict]:
    """name -> {version, hashes} for every pinned entry in the lock file.

    Continuation lines are joined implicitly: a package line starts a block,
    ``--hash=sha256:`` lines extend it, comments are ignored.
    """
    graph: dict[str, dict] = {}
    current: str | None = None
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        line = line.rstrip("\\").strip()
        if "--hash" in line:
            if current is None:
                raise AssertionError(f"hash line before any package pin: {raw!r}")
            graph[current]["hashes"].extend(
                re.findall(r"--hash=sha256:([0-9a-f]{64})", line)
            )
            continue
        match = re.match(r"^([A-Za-z0-9._-]+)==(\S+)$", line)
        if match is None:
            raise AssertionError(f"unparsable lock line: {raw!r}")
        current = canonical_name(match.group(1))
        graph[current] = {"version": match.group(2), "hashes": []}
    return graph


def hash_set_digest(hashes: list[str]) -> str:
    """Deterministic digest of a package's hash set (sorted, newline-joined)."""
    return hashlib.sha256("\n".join(sorted(hashes)).encode("utf-8")).hexdigest()


def load_baseline() -> dict:
    return json.loads(BASELINE_PATH.read_text(encoding="utf-8"))


class ManifestOracleTests(unittest.TestCase):
    """Direct manifest: exactly one OpenCV distribution, no headless string.

    RED pre-change: ``opencv-python-headless==5.0.0.93`` is still a manifest
    line, so both the single-pin list and the headless absence fail.
    """

    def test_direct_manifest_pins_exactly_one_opencv_distribution(self) -> None:
        text = REQUIREMENTS.read_text(encoding="utf-8")
        pins = [
            line.strip()
            for line in text.splitlines()
            if re.match(r"opencv[a-z0-9._-]*==", line.strip(), re.IGNORECASE)
        ]
        self.assertEqual(pins, [DIRECT_OPENCV_PIN])
        self.assertIn(DIRECT_OPENCV_PIN, text)
        self.assertNotIn(HEADLESS_DISTRIBUTION, text)


class LockGraphOracleTests(unittest.TestCase):
    """Lock graph: one OpenCV provider, 56 packages, only headless removed.

    RED pre-change: 57 packages with the headless entry and its nine wheel
    hashes still present, so every count/set/absence oracle here fails.
    """

    def test_lock_carries_exactly_one_opencv_provider(self) -> None:
        graph = parse_lock_graph(LOCK_FILE.read_text(encoding="utf-8"))
        providers = sorted(name for name in graph if name.startswith("opencv"))
        self.assertEqual(providers, ["opencv-python"])
        self.assertEqual(graph["opencv-python"]["version"], "5.0.0.93")
        self.assertNotIn(HEADLESS_DISTRIBUTION, graph)

    def test_lock_graph_is_the_pre_change_graph_minus_headless(self) -> None:
        baseline = load_baseline()
        text = LOCK_FILE.read_text(encoding="utf-8")
        graph = parse_lock_graph(text)

        # Counts, both sides literal: 57 -> 56 packages, 1120 -> 1111 pins.
        self.assertEqual(baseline["package_count"], PRE_CHANGE_PACKAGE_COUNT)
        self.assertEqual(baseline["hash_count"], PRE_CHANGE_HASH_PIN_COUNT)
        self.assertEqual(len(graph), PACKAGE_COUNT)
        total_pins = sum(len(entry["hashes"]) for entry in graph.values())
        self.assertEqual(total_pins, HASH_PIN_COUNT)
        self.assertEqual(PRE_CHANGE_HASH_PIN_COUNT - HEADLESS_HASH_COUNT, HASH_PIN_COUNT)

        # Name set: exactly the headless entry removed, nothing added.
        self.assertEqual(baseline["removed_package"], HEADLESS_DISTRIBUTION)
        expected_names = set(baseline["packages"]) - {HEADLESS_DISTRIBUTION}
        self.assertEqual(set(graph), expected_names)

        # Every surviving package keeps its version and its exact hash set
        # (compared via the baseline digest — raw hashes are not duplicated).
        for name, entry in sorted(graph.items()):
            base = baseline["packages"][name]
            self.assertEqual(entry["version"], base["version"], name)
            self.assertEqual(len(entry["hashes"]), base["hash_count"], name)
            self.assertEqual(hash_set_digest(entry["hashes"]), base["hash_set_sha256"], name)

        # The specific removal: headless and its nine wheel hashes are gone
        # from the whole file, not merely renamed.
        removed = baseline["packages"][HEADLESS_DISTRIBUTION]
        self.assertEqual(removed["hash_count"], HEADLESS_HASH_COUNT)
        self.assertEqual(len(removed["hashes"]), HEADLESS_HASH_COUNT)
        self.assertNotIn(f"{HEADLESS_DISTRIBUTION}==", text)
        for wheel_hash in removed["hashes"]:
            self.assertNotIn(wheel_hash, text)

    def test_torch_and_torchvision_pins_and_hash_sets_survive(self) -> None:
        baseline = load_baseline()
        graph = parse_lock_graph(LOCK_FILE.read_text(encoding="utf-8"))
        for pin, artifact in (
            (TORCH_PIN, TORCH_ARTIFACT_SHA256),
            (TORCHVISION_PIN, TORCHVISION_ARTIFACT_SHA256),
        ):
            name, _, version = pin.partition("==")
            self.assertIn(name, graph, pin)
            self.assertEqual(graph[name]["version"], version, pin)
            self.assertIn(artifact, graph[name]["hashes"], pin)
            self.assertEqual(
                hash_set_digest(graph[name]["hashes"]),
                baseline["packages"][name]["hash_set_sha256"],
                f"{name} hash set drifted from the pre-change lock",
            )


class DigestBindingTests(unittest.TestCase):
    """runtime-lock.json binds the final lockfile bytes by sha256.

    RED pre-change: ``resolved_lock.sha256`` is the pre-change digest
    ``e20d7652...``, so the literal binding fails (the computed-vs-recorded
    equality itself is a live cross-check either way).
    """

    def test_resolved_lock_sha256_binds_the_lockfile_bytes(self) -> None:
        lock = json.loads(RUNTIME_LOCK.read_text(encoding="utf-8"))
        computed = hashlib.sha256(LOCK_FILE.read_bytes()).hexdigest()
        self.assertEqual(computed, lock["resolved_lock"]["sha256"])
        self.assertEqual(computed, LOCK_SHA256)
        self.assertEqual(lock["resolved_lock"]["file"], "requirements-runtime.lock.txt")
        # The binding moved with the landing; the old digest must not match.
        self.assertNotEqual(computed, PRE_CHANGE_LOCK_SHA256)

    def test_single_byte_change_breaks_the_digest_check(self) -> None:
        lock = json.loads(RUNTIME_LOCK.read_text(encoding="utf-8"))
        stored = lock["resolved_lock"]["sha256"]
        mutated = bytearray(LOCK_FILE.read_bytes())
        mutated[0] ^= 0x01
        mutated_digest = hashlib.sha256(bytes(mutated)).hexdigest()
        self.assertNotEqual(mutated_digest, stored)
        self.assertNotEqual(mutated_digest, LOCK_SHA256)
        self.assertNotEqual(mutated, LOCK_FILE.read_bytes())

    def test_cuda_artifact_digests_and_verification_imports_preserved(self) -> None:
        lock = json.loads(RUNTIME_LOCK.read_text(encoding="utf-8"))
        self.assertEqual(
            lock["pytorch"]["artifact_sha256"],
            {"torch": TORCH_ARTIFACT_SHA256, "torchvision": TORCHVISION_ARTIFACT_SHA256},
        )
        self.assertEqual(
            lock["pytorch"]["packages"],
            {"torch": "2.13.0+cu130", "torchvision": "0.28.0+cu130"},
        )
        self.assertEqual(lock["pytorch"]["index_url"], PYTORCH_INDEX_URL)
        self.assertEqual(lock["verification_imports"], VERIFICATION_IMPORTS)


class NoDriftTests(unittest.TestCase):
    """No surviving pin moved; canonical header/marker; no -c annotations.

    RED pre-change: the pin set still contains the headless pin (57 entries),
    so the pin-set equality fails; the header/marker and annotation bans are
    keeps that guard the regenerated file either way.
    """

    def test_no_surviving_pin_version_changed(self) -> None:
        baseline = load_baseline()
        graph = parse_lock_graph(LOCK_FILE.read_text(encoding="utf-8"))
        self.assertEqual(len(graph), PACKAGE_COUNT)
        self.assertEqual(
            set(graph),
            set(baseline["packages"]) - {HEADLESS_DISTRIBUTION},
        )
        for name, entry in sorted(graph.items()):
            self.assertEqual(
                entry["version"],
                baseline["packages"][name]["version"],
                f"pin version drifted from the pre-change lock: {name}",
            )

    def test_canonical_header_and_lock_marker_present(self) -> None:
        text = LOCK_FILE.read_text(encoding="utf-8")
        lines = text.splitlines()
        self.assertTrue(text.startswith(LOCK_MARKER + "\n"))
        self.assertEqual(lines[0], LOCK_MARKER)
        self.assertEqual(lines[1], UV_HEADER)
        self.assertIn(UV_COMMAND_FRAGMENT, lines[2])

    def test_no_temporary_constraint_annotations_in_via_comments(self) -> None:
        text = LOCK_FILE.read_text(encoding="utf-8")
        # The controlled regeneration pinned survivors in a temporary `-c`
        # constraints file; no such annotation may survive in the output.
        offenders = [
            line
            for line in text.splitlines()
            if re.search(r"(^|\s)-c(\s|$)", line) or "constraint" in line.lower()
        ]
        self.assertEqual(offenders, [])


class ScopeGuardTests(unittest.TestCase):
    """Change surface: no waiver, no workflow/API-lockfile churn, SDD present.

    The SDD/NO-WAIVER test is RED pre-change (the trio does not exist); the
    waiver-file and changed-path tests are keeps that fail the moment a
    waiver/exception file or an out-of-scope path appears.
    """

    def _changed_paths(self) -> list[str]:
        result = subprocess.run(
            ["git", "-C", str(ROOT), "status", "--porcelain", "--untracked-files=all"],
            capture_output=True,
            text=True,
            check=True,
        )
        paths: list[str] = []
        for line in result.stdout.splitlines():
            if not line.strip():
                continue
            path = line[3:]
            if " -> " in path:  # rename entries carry old -> new
                path = path.split(" -> ")[-1]
            paths.append(path.strip().strip('"'))
        return paths

    def test_no_waiver_or_exception_file_exists(self) -> None:
        offenders: list[str] = []
        for dirpath, dirnames, filenames in os.walk(ROOT):
            dirnames[:] = [d for d in dirnames if d not in WAIVER_SCAN_PRUNED_DIRS]
            for filename in filenames:
                lowered = filename.lower()
                if "waiver" in lowered or "exception" in lowered:
                    relative = Path(dirpath, filename).relative_to(ROOT)
                    offenders.append(str(relative))
        self.assertEqual(offenders, [], "waiver/exception artifacts present")

    def test_no_workflow_or_api_lockfile_changed(self) -> None:
        changed = self._changed_paths()
        offenders = [
            path
            for path in changed
            if not any(path.startswith(prefix) for prefix in ALLOWED_CHANGE_PREFIXES)
        ]
        self.assertEqual(
            offenders,
            [],
            f"out-of-scope working-tree changes (workflows/API lockfiles must stay untouched): {offenders}",
        )
        for forbidden in (".github/", "api/requirements-api.lock.txt", "package-lock.json"):
            self.assertFalse(
                any(path.startswith(forbidden) for path in changed),
                f"forbidden path changed: {forbidden}",
            )

    def test_sdd_trio_exists_and_records_no_waiver(self) -> None:
        texts: dict[str, str] = {}
        for name in ("spec.md", "plan.md", "tasks.md"):
            path = SDD_DIR / name
            self.assertTrue(path.is_file(), f"missing SDD artifact: {path}")
            texts[name] = path.read_text(encoding="utf-8")
        self.assertIn(
            "NO WAIVER is requested, proposed or granted",
            texts["spec.md"],
        )
        self.assertIn("no waiver", texts["plan.md"].lower())
        self.assertIn("no waiver", texts["tasks.md"].lower())


