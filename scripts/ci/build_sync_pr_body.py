#!/usr/bin/env python3
"""Build the deterministic Change-Contract PR body for the tasks.md auto-sync PR.

Used by .github/workflows/sync-merged-tasks.yml (issue #477): when a green push
to main leaves unchecked completion markers in specs/*/tasks.md, the workflow
creates (or updates) the chore/tasks-md-auto-sync PR whose body must satisfy
scripts/ci/validate_change_contract.py (PR Validation + Quality integration gate
both validate it on pull_request). This generator emits that body:

- Changed files: the exact tasks.md delta the sync commit carries (the
  validator compares the declared list against the PR's git diff, byte-exact).
- Derived impact: specs/** matches no policy pattern, so the Change Contract
  must declare Production impact NONE, no deployment contours, execution
  capabilities NOT APPLICABLE and Operator actions expected 0 — exactly what
  this template pins (breaking the template in sync with the policy is caught
  by tests/test_sync_tasks_md_flow.py, which runs the real validator).

Usage:
  python scripts/ci/build_sync_pr_body.py --source-sha <full-or-8> \
      --changed-file specs/477-sync-tasks-pr-flow/tasks.md [--changed-file ...] \
      [--out PATH]        # default: stdout
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

SOURCE_AUTHORIZATION = "commit approved"
ISSUE_REF = "#477"


def build_body(source_sha: str, changed_files: list[str]) -> str:
    sha8 = source_sha[:8]
    files_block = "\n".join(f"  - `{path}`" for path in changed_files)
    if not files_block:
        raise SystemExit("build_sync_pr_body: no changed files supplied")
    return f"""## Canonical task

- Issue: {ISSUE_REF}
- Flow: automated tasks.md completion-marker sync generated by .github/workflows/sync-merged-tasks.yml (established by #477). Source merge that triggered this sync: {source_sha}.

## Change

- Changed files:
{files_block}
- Out of scope: everything else. This PR only flips recognized completion markers via scripts/ci/sync_tasks_md.py (never unchecks, never edits task content) as the PR-based replacement for the direct-to-main push that repository rulesets decline (#477).

## Impact

- Production impact: NONE
- Production-impact rationale: docs-only SDD completion-marker flips under specs/*/tasks.md; no runtime code path, no deploy contour, no schema, no secrets.
- Security impact: NONE
- API/event/state/storage schema impact: NONE
- Detection/tracking/calibration/speed formula impact: NONE
- Backward compatibility: marker-only documentation change; no behavior anywhere.
- Destructive/data migration impact: NO
- Other high-risk trigger: NO
- VPS deployment: NOT REQUIRED
- Ubuntu worker/relay update: NOT REQUIRED
- Production safety envelope: NOT REQUIRED
- VPS execution capability: NOT APPLICABLE
- Ubuntu worker execution capability: NOT APPLICABLE
- Operator actions expected: 0

## Delivery

- Source authorization: {SOURCE_AUTHORIZATION}
- Approval recorded after Implementation Scope Check: YES
- Material scope/protected-boundary change since authorization: NO
- Approved scope: flip recognized tasks.md completion markers for the spec dirs changed by merge {sha8}, via the deterministic chore/tasks-md-auto-sync PR flow (#477).
- Acceptance criteria: after this PR's squash merge, scripts/ci/validate_sdd.py --freshness is green for the merged specs' tasks.md and main carries no unchecked recognized completion markers for them; the follow-up sync run reports "all changed tasks.md already current" and creates no new PR.
- Intended behavior: main carries checked completion markers for every merged spec (validate_sdd --freshness green) without any direct-to-main push.
- Rollout order: this PR is created/updated by the sync workflow, merges itself after its own required checks are green; a declined merge fails the sync run loudly.
- Release manifest: NONE
- Rollback target: revert the squash commit on main (docs-only); no runtime rollback contour.
- Risk profile: NOT REQUIRED
- Quality verdict: PASS
- Quality finding: NONE
- Waiver reason: NONE
- Waiver approved by: NONE
- Waiver review/expiry date: NONE
- Waiver compensating controls: NONE
- Waiver follow-up/remediation target: NONE

## Validation

- Local checks: scripts/ci/sync_tasks_md.py marker round-trip is a no-op on already-synced files (tests/test_sync_tasks_md_flow.py); scripts/ci/validate_sdd.py --freshness green against the source merge.
- PR checks: PR Validation and Quality integration gate run on this PR and satisfy the repository ruleset's required PR checks; the sync workflow merges only when they are green.
- Runtime acceptance plan: NONE
- Telemetry/evidence plan: the sync workflow run log is the evidence (merged green, or a loud non-zero exit naming the PR URL).

## Completion

- Loop safety: this PR's squash merge contains only already-flipped markers; the next sync run re-runs scripts/ci/sync_tasks_md.py against that diff and reports "all changed tasks.md already current", so no new PR is created.
- Contour: NONE (control-plane housekeeping only; deploys do not depend on this workflow).
"""


def main() -> int:
    parser = argparse.ArgumentParser(description="Build the auto-sync PR body (Change-Contract compliant).")
    parser.add_argument("--source-sha", required=True, help="Full SHA of the source merge being synced.")
    parser.add_argument(
        "--changed-file",
        action="append",
        default=[],
        dest="changed_files",
        help="Changed tasks.md path; repeat for each file.",
    )
    parser.add_argument("--out", type=Path, help="Write the body here (default: stdout).")
    args = parser.parse_args()
    if len(args.source_sha) < 8:
        raise SystemExit("build_sync_pr_body: --source-sha must be at least 8 hex chars")
    body = build_body(args.source_sha, args.changed_files)
    if args.out:
        args.out.write_text(body, encoding="utf-8")
    else:
        sys.stdout.write(body)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
